import { DEFAULT_META, SITE_URL, SITE_NAME, DEFAULT_IMAGE } from '../data/seo';

function setMeta(attr, key, content) {
  let el = document.head.querySelector(`meta[${attr}="${key}"]`);
  if (!el) {
    el = document.createElement('meta');
    el.setAttribute(attr, key);
    document.head.appendChild(el);
  }
  el.setAttribute('content', content);
}

function setCanonical(href) {
  let el = document.head.querySelector('link[rel="canonical"]');
  if (!el) {
    el = document.createElement('link');
    el.setAttribute('rel', 'canonical');
    document.head.appendChild(el);
  }
  el.setAttribute('href', href);
}

export function applyMeta(meta, pathname) {
  const title = meta.title;
  const description = meta.description || DEFAULT_META.description;
  const canonical = SITE_URL + (pathname.length > 1 ? pathname.replace(/\/+$/, '') : '');

  document.title = title;
  setMeta('name', 'description', description);
  setMeta('name', 'robots', meta.noindex ? 'noindex, nofollow' : 'index, follow');
  setCanonical(canonical);

  setMeta('property', 'og:type', 'website');
  setMeta('property', 'og:site_name', SITE_NAME);
  setMeta('property', 'og:locale', 'es_ES');
  setMeta('property', 'og:title', title);
  setMeta('property', 'og:description', description);
  setMeta('property', 'og:url', canonical);
  setMeta('property', 'og:image', meta.image || DEFAULT_IMAGE);
  setMeta('name', 'twitter:card', 'summary_large_image');
}
